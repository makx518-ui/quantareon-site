def _имя_валюты(код: str) -> str:
    """Название вместо кода — иначе движок речи читает GEL как «лей»."""
    имя = _ИМЕНА_ВАЛЮТ.get(код)
    return f"{имя} ({код})" if имя else код


async def _курс(реплика: str, lang: str = "ru") -> str:
    """Точный курс валют — open.er-api.com, без ключа.

    БЫЛО: валюта уходила в обычный поиск, и Tavily приносил СТАТЬЮ о курсе.
    Проверено 07.08 — помощник назвал доллар 76,9 ₽, тогда как настоящий
    курс был 81,3. Статья о деньгах и сами деньги — разные вещи.
    """
    import aiohttp
    т = (реплика or "").lower()
    # порядок берём ИЗ РЕПЛИКИ, а не из словаря: «лари к рублю» — это
    # лари в базе, а не наоборот
    попались = []
    for сл, код in _ВАЛЮТЫ_КОДЫ.items():
        поз = т.find(сл)
        if поз >= 0:
            попались.append((поз, код))
    найдены = []
    for _, код in sorted(попались):
        if код not in найдены:
            найдены.append(код)
    if not найдены:
        return ""
    база = найдены[0]
    цели = найдены[1:] or (["GEL", "RUB", "EUR"] if база != "USD" else ["GEL", "RUB", "EUR"])
    цели = [ц for ц in _убрать_базу(цели, база)]
    try:
        async with aiohttp.ClientSession() as s:
            async with s.get(f"https://open.er-api.com/v6/latest/{база}",
                             timeout=aiohttp.ClientTimeout(total=10)) as r:
                d = await r.json()
        курсы = d.get("rates") or {}
        if not курсы:
            return ""
        обновлён = (d.get("time_last_update_utc") or "")[:22]
        строки = []
        for ц in цели:
            зн = курсы.get(ц)
            if зн:
                # ⚠️ Пишем НАЗВАНИЕ, а не код: 07.08 помощник прочитал «GEL»
                # как молдавский лей вместо грузинского лари
                строки.append(f"• 1 {_имя_валюты(база)} = {зн:.4f} {_имя_валюты(ц)}"
                              .rstrip("0").rstrip("."))
        if not строки:
            return ""
        подпись = "[EXCHANGE RATE]" if lang == "en" else "[КУРС ВАЛЮТ СЕЙЧАС]"
        хвост = (f"\nUpdated: {обновлён}" if lang == "en"
                 else f"\nОбновлено: {обновлён}")
        return подпись + "\n" + "\n".join(строки) + хвост
    except Exception as e:
        logger.warning(f"курс не вышел: {e}")
        return ""


def _убрать_базу(цели, база):
    вышло = []
    for ц in цели:
        if ц != база and ц not in вышло:
            вышло.append(ц)
    return вышло or ["USD"]


async def _крипта(реплика: str, lang: str = "ru") -> str:
    """Цена монеты — Coinbase spot, без ключа.

    CoinGecko с общего адреса отдаёт 429, Binance — 451 (регион),
    Coinbase отвечает стабильно. Проверено 07.08.
    """
    import aiohttp
    т = (реплика or "").lower()
    монеты = []
    for сл, код in _КРИПТА_КОДЫ.items():
        if сл in т and код not in монеты:
            монеты.append(код)
    if not монеты:
        монеты = ["BTC"]
    строки = []
    try:
        async with aiohttp.ClientSession() as s:
            for код in монеты[:3]:
                async with s.get(f"https://api.coinbase.com/v2/prices/{код}-USD/spot",
                                 timeout=aiohttp.ClientTimeout(total=10)) as r:
                    if r.status != 200:
                        continue
                    d = await r.json()
                сумма = ((d.get("data") or {}).get("amount"))
                if сумма:
                    строки.append(f"• 1 {код} = {float(сумма):,.2f} USD".replace(",", " "))
        if not строки:
            return ""
        подпись = "[CRYPTO PRICE]" if lang == "en" else "[ЦЕНА КРИПТОВАЛЮТЫ СЕЙЧАС]"
        return подпись + "\n" + "\n".join(строки)
    except Exception as e:
        logger.warning(f"крипта не вышла: {e}")
        return ""


async def _новости(запрос: str, сайты=None, lang: str = "ru") -> str:
    """NewsData — живая лента с датой и источником. Точнее поиска."""
    import aiohttp
    # ключ берём из переменной, а если её нет — из web_tools
    # (репозиторий закрытый, ключи лежат там; см. пояснение в web_tools.py)
    ключ = os.getenv("NEWSDATA_API_KEY", "")
    if not ключ:
        try:
            import web_tools as _WT
            ключ = _WT._ключ("NEWSDATA_API_KEY")
        except Exception:
            ключ = ""
    if not ключ:
        return ""
    try:
        язык = "en" if lang == "en" else "ru"
        # ⚠️ размер берём с запасом: часть заголовков отсеет фильтр по сути
        url = f"https://newsdata.io/api/1/latest?apikey={ключ}&language={язык}&size=10"
        суть = _суть_новостей(запрос)
        if суть and len(суть) > 2:
            from urllib.parse import quote
            url += f"&q={quote(суть[:100])}"
        if сайты:
            url += f"&domain={','.join(d.split('.')[0] for d in сайты)}"
        async with aiohttp.ClientSession() as s:
            async with s.get(url, timeout=aiohttp.ClientTimeout(total=10)) as r:
                d = await r.json()
        строки = []
        for н in (d.get("results") or []):
            дата = (н.get("pubDate") or "")[:16]
            строки.append(f"• {н.get('title','')} ({н.get('source_name','')}, {дата})")
        строки = _лента_по_сути(строки, суть)[:4]
        # ничего по делу не нашлось — молчим, и собрать() уронит нас в Tavily
        if not строки:
            return ""
        подпись = "[NEWS FEED]" if lang == "en" else "[НОВОСТИ ИЗ ЛЕНТЫ]"
        return подпись + "\n" + "\n".join(строки)
    except Exception as e:
        logger.warning(f"новости не вышли: {e}")
        return ""


async def собрать(реплика: str, lang: str = "ru", решение: Optional[Dict[str, Any]] = None) -> str:
    """Главный вход. Реплика → блок для промпта (или пустая строка).

    Ничего не решает за модель: только приносит факты. Что с ними
    делать, сказано в промпте.
    """
    р = решение if решение is not None else разобрать(реплика)
    if not р["идём"]:
        return ""

    тема, сайты = р["тема"], р["сайты"]
    # запрос судьи точнее нашей очистки: он уже без слов-просьб и по сути
    запрос = (р.get("запрос_судьи") or "").strip() or очистить_запрос(реплика) or реплика

    # ⚠️ МУСОР ОТ РАСПОЗНАВАНИЯ — ГЛАВНАЯ БЕДА ЖИВОЙ РЕЧИ.
    # «Какие новости в мире БРАК посмотри в интернете» (человек сказал «брат»)
    # → механическая очистка выбрасывает «какие», «новости», «в мире»,
    # «посмотри», «в интернете» как служебные, и запросом остаётся «брак».
    # Прошлая правка спасала, только если лента пуста; если же по мусорному
    # слову что-то НАХОДИЛОСЬ — мусор проходил дальше, и помощник
    # переспрашивал, потому что данные не по теме.
    # ЛЕЧЕНИЕ: для тем, где запрос — свободный текст, формулировку берём у
    # судьи. Он смотрит на фразу целиком и выбрасывает покорёженное слово
    # сам. Стоит ~0.2 сек, зато ответ перестаёт зависеть от одной ослышки.
    # ⏱️ СУДЬЯ РАБОТАЕТ ПАРАЛЛЕЛЬНО, А НЕ В ОЧЕРЕДИ.
    # Он чистит мусор распознавания («…в мире брак посмотри») — вещь нужная,
    # но человек ждёт ответа. Раньше он стоял ПЕРЕД поиском и его секунда
    # прибавлялась к секунде поиска. Теперь запускаем его фоном, идём искать
    # сразу, и заглядываем к нему только если своя очистка не сработала.
    задача_судьи = None
    if (тема in ("новости", "поиск", "финансы", "экономика", "спорт")
            and _СУДЬЯ_ВКЛ and not (р.get("запрос_судьи") or "").strip()):
        try:
            задача_судьи = asyncio.create_task(_судья(реплика, lang))
        except Exception:
            задача_судьи = None

    async def спросить_судью():
        """Забрать готовый ответ судьи (он считался всё это время)."""
        nonlocal задача_судьи
        if задача_судьи is None:
            return None
        try:
            return await asyncio.wait_for(
                задача_судьи,
                timeout=float(os.getenv("SUDYA_QUERY_TIMEOUT", "1.2")))
        except Exception:
            logger.info("судья не успел — идём со своей очисткой")
            return None
        finally:
            задача_судьи = None

    def отпустить_судью():
        if задача_судьи is not None and not задача_судьи.done():
            задача_судьи.cancel()

    # время считаем на месте, без сети
    if тема == "время":
        return ""      # филлер и так называет дату и время

    if тема == "погода":
        return await _погода(реплика, lang)

    # валюта и крипта — сперва прямой источник с настоящей цифрой,
    # и только если он молчит, падаем в обычный поиск
    if тема == "валюта":
        цифра = await _курс(реплика, lang)
        if цифра:
            return цифра

    if тема == "крипта":
        цифра = await _крипта(реплика, lang)
        if цифра:
            return цифра

    if тема == "новости":
        лента = await _новости(запрос, сайты, lang)
        if лента:
            отпустить_судью()          # своя очистка справилась — не ждём
            return лента

        # ⚠️ ЛЕНТА ПУСТА — НЕ ТАЩИМ ОГРЫЗОК ДАЛЬШЕ.
        # Случай 07.08: распознавание услышало «Поэти, какие новости в мире»,
        # очистка выбросила «какие», «новости», «в мире» как служебные, и
        # единственным словом запроса осталось мусорное «Поэти» — помощник
        # ушёл искать поэзию. Мусор в запросе опаснее пустого запроса.
        if not лента:
            суть = _суть_новостей(запрос)
            слов = len(суть.split())

            # ⚠️ ВТОРОГО ВЫЗОВА СУДЬИ ЗДЕСЬ НЕТ.
            # Раньше стоял — и удваивал задержку: судья уже сформулировал
            # запрос выше, звать его снова было чистой потерей секунды.
            # Замер 07.08: «Найди новости Грузии» — 2037мс с двойным вызовом
            # против 754мс без него.

            # 1) заглядываем к судье — он считался параллельно, ждать почти нечего
            с = await спросить_судью()
            нов = ((с or {}).get("запрос") or "").strip()
            if нов and нов.lower() != (запрос or "").strip().lower():
                лента = await _новости(нов, сайты, lang)
                if лента:
                    запрос = нов

            # 2) пусто, а спрашивали общо («что в мире») или
            #    осталось одно невнятное слово — берём общую ленту,
            #    это честнее, чем поиск по случайному слову
            if not лента and (слов <= 1 or "мир" in (реплика or "").lower()):
                лента = await _новости("", сайты, lang)
                if лента:
                    запрос = ""

        if лента:
            return лента
        # лента совсем пуста — падаем в обычный поиск

    # ── остальное: поиск ──
    # здесь запрос идёт в общий поиск, и формулировка судьи полезна:
    # он уже посчитал, ждать почти нечего
    с = await спросить_судью()
    нов = ((с or {}).get("запрос") or "").strip()
    if нов:
        запрос = нов
        тема_с = (с or {}).get("тема")
        if тема_с and тема_с not in ("нет",):
            тема = тема_с

    try:
        import web_tools as WT
    except ImportError:
        return ""

    # ⚠️ ДВЕ ХИТРОСТИ, найдены опытом:
    # 1) без страны Tavily путает Грузию-страну со штатом Джорджия и приносит
    #    новости Атланты вместо Тбилиси;
    # 2) на русский вопрос он всё равно отвечает по-английски — лечится
    #    прямой просьбой прямо в тексте запроса.
    # Страна: на русской версии сайта человек чаще в Грузии — без этого
    # Tavily путал страну Грузию со штатом Джорджия и нёс новости Атланты.
    # На английской версии страну не задаём: аудитория со всего мира.
    страна = "georgia" if lang == "ru" else None
    # Язык ответа: Tavily по русскому вопросу всё равно отвечает по-английски,
    # лечится прямой просьбой в тексте запроса. Английской версии это не нужно.
    if lang == "ru":
        запрос = запрос + ". Ответь на русском языке."
    тема_поиска = "news" if тема == "новости" else (
        "finance" if тема in ("валюта", "крипта", "финансы", "экономика") else "general")

    try:
        r = await WT.tavily_search(
            запрос, max_results=3, topic=тема_поиска,
            include_answer=True,
            include_domains=сайты,
            country=страна,
            time_range="day" if тема in ("новости", "валюта", "крипта") else None,
        )
        if not r.get("success") or not r.get("results"):
            r = await WT.serper_search(запрос, max_results=3)
        if not r.get("success") or not r.get("results"):
            r = await WT.ddg_search(запрос, max_results=3)
        if not r.get("success"):
            return ""
        подпись = "🌐 CURRENT INFORMATION" if lang == "en" else "🌐 АКТУАЛЬНАЯ ИНФОРМАЦИЯ"
        if сайты:
            подпись += (f" (searched on {', '.join(сайты)})" if lang == "en"
                        else f" (искали на {', '.join(сайты)})")
        return WT.format_for_prompt(r, label=подпись, max_chars=1800)
    except Exception as e:
        logger.warning(f"поиск не вышел: {e}")
        return ""
