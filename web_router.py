_ДОМЕН = re.compile(
    r"\b([a-z0-9\-]+\.(?:ru|com|org|net|ge|io|dev|info|news|tv|me|ua|by|kz))\b",
    re.IGNORECASE)


def _есть(текст: str, слова: List[str]) -> bool:
    return any(с in текст for с in слова)


def найти_сайт(текст: str) -> Optional[List[str]]:
    """Не назвал ли человек сайт, по которому искать.

    Три способа: прямой адрес, «на сайте такой-то», знакомое имя издания.
    """
    # 1. прямая ссылка
    м = _АДРЕС.search(текст)
    if м:
        адрес = м.group(0).rstrip(".,!?)")
        дом = адрес.split("//")[-1].split("/")[0]
        return [дом] if дом else None

    # 2. голый домен без протокола
    м = _ДОМЕН.search(текст)
    if м:
        return [м.group(1).lower()]

    # 3. «на сайте ...»
    м = _НА_САЙТЕ.search(текст)
    if м:
        имя = м.group(1).lower().strip(".,")
        # если назвали знакомое имя — берём его домен
        for ключ, дом in _САЙТЕ_ключи():
            if ключ in имя:
                return [дом]
        # иначе считаем доменом как есть, если похоже на домен
        if "." in имя:
            return [имя]
        return None

    # 4. знакомое имя издания где угодно в реплике
    for ключ, дом in _САЙТЕ_ключи():
        if ключ in текст:
            return [дом]
    return None


def _САЙТЕ_ключи():
    # длинные ключи первыми: «википеди» раньше «вики»
    return sorted(_САЙТЫ.items(), key=lambda п: -len(п[0]))


def разобрать(реплика: str) -> Dict[str, Any]:
    """Главная функция: что делать с этой репликой.

    Возвращает:
        {
          "идём":    True/False      — нужен ли интернет вообще
          "тема":    "погода" | "время" | "валюта" | "крипта" |
                     "новости" | "финансы" | "экономика" | "спорт" | "поиск"
          "сайты":   ["lenta.ru"] или None
          "просили": True/False      — была ли явная просьба искать
        }
    """
    т = (реплика or "").lower()

    просили = _есть(т, _ПРОСЬБА_ИСКАТЬ)
    сайты = найти_сайт(т)

    # ── САМОСТОЯТЕЛЬНЫЕ: идут без просьбы ──
    if _есть(т, _ВРЕМЯ):
        return {"идём": True, "тема": "время", "сайты": None, "просили": просили}
    if _есть(т, _ПОГОДА):
        return {"идём": True, "тема": "погода", "сайты": None, "просили": просили}
    if _есть(т, _ВАЛЮТА):
        return {"идём": True, "тема": "валюта", "сайты": сайты, "просили": просили}
    if _есть(т, _КРИПТА):
        return {"идём": True, "тема": "крипта", "сайты": сайты, "просили": просили}
    # новости тоже идут сами — но не когда это бытовой оборот
    if _есть(т, _НОВОСТИ_САМИ) and not _есть(т, _НЕ_НОВОСТИ):
        return {"идём": True, "тема": "новости", "сайты": сайты, "просили": просили}

    # ── Назвали сайт + глагол поиска = явная просьба ──
    # «найди на Ленте», «что пишут на Би-би-си» — слова «интернет» тут нет,
    # но названный сайт не оставляет сомнений, чего от нас хотят.
    if сайты and (просили or _есть(т, _ГЛАГОЛЫ_ПОИСКА) or _есть(т, _НОВОСТИ)):
        тема = "новости" if _есть(т, _НОВОСТИ) else "поиск"
        return {"идём": True, "тема": тема, "сайты": сайты, "просили": True}

    # ── ГЛАГОЛ ПОИСКА САМ ПО СЕБЕ = ПРОСЬБА ИСКАТЬ ──
    # Человек говорит «Найди новости», а не «Найди в интернете новости».
    # Раньше короткий глагол пускал в сеть ТОЛЬКО вместе с названным сайтом,
    # поэтому самая частая живая фраза молча проваливалась мимо интернета,
    # и модель начинала переспрашивать «уточните тему».
    if _есть(т, _ГЛАГОЛЫ_ПОИСКА):
        просили = True

    # ── ОСТАЛЬНОЕ: только по явной просьбе ──
    if not просили:
        return {"идём": False, "тема": None, "сайты": None, "просили": False}

    if _есть(т, _НОВОСТИ):
        тема = "новости"
    elif _есть(т, _ФИНАНСЫ):
        тема = "финансы"
    elif _есть(т, _ЭКОНОМИКА):
        тема = "экономика"
    elif _есть(т, _СПОРТ):
        тема = "спорт"
    else:
        тема = "поиск"

    return {"идём": True, "тема": тема, "сайты": сайты, "просили": True}


