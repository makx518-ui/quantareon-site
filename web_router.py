def _пахнет_миром(реплика: str) -> bool:
    """Стоит ли будить судью. Дёшево и без сети.

    Ошибиться в одну сторону не страшно: не разбудили — помощник ответит
    сам, как отвечал всегда. Ошибиться в другую — человек ждёт лишнюю
    секунду на пустом месте, а это он замечает сразу.
    """
    т = (реплика or "").lower()
    if not т.strip():
        return False
    # наши владения и разговор о самом помощнике — сеть не нужна никогда,
    # эти два списка проверяем ПЕРВЫМИ и они сильнее примет мира
    if _есть(т, _НАШЕ):
        return False
    if _есть(т, _ПРО_СЕБЯ):
        return False
    if _есть(т, _ПРИМЕТЫ_МИРА):
        return True
    # имя собственное посреди фразы (не первое слово) — вероятно, спрашивают
    # о человеке, месте или компании
    слова = re.findall(r"[А-ЯЁA-Z][а-яёa-z]{3,}", реплика or "")
    первое = (реплика or "").strip().split(" ")[:1]
    if слова and not (len(слова) == 1 and первое and слова[0] in первое[0]):
        return True
    return False


async def решить(реплика: str, lang: str = "ru") -> Dict[str, Any]:
    """Итоговое решение: сперва мгновенные списки, потом судья.

    Списки покрывают явное и стоят 0 мс. Судья включается ТОЛЬКО когда они
    промолчали — то есть на обычных «найди новости» задержки не появляется.
    """
    р = разобрать(реплика)
    if р.get("идём"):
        return р
    if not _СУДЬЯ_РЕШАЕТ:
        return р
    т = (реплика or "").lower().strip()
    # короткая явная болтовня — незачем будить судью
    if len(т) <= 30 and _есть(т, _БОЛТОВНЯ):
        return р
    # ⚡ ГЛАВНОЕ ПРАВИЛО СКОРОСТИ: судья — сетевой вызов, он стоит на пути
    # ответа. Замер 07.08: на «Что ты умеешь?» он думал 777 мс, чтобы в
    # конце сказать «искать не надо». Человек это слышит как потерю
    # реалтайма. Поэтому будим его ТОЛЬКО когда в реплике есть хоть один
    # признак вопроса о внешнем мире.
    if not _пахнет_миром(реплика):
        return р
    с = await _судья(реплика, lang)
    if с and с.get("искать"):
        тема = с.get("тема") or "поиск"
        if тема == "нет":
            тема = "поиск"
        logger.info(f"🧠 судья: идём в сеть, тема {тема}, запрос {с.get('запрос','')!r}")
        return {
            "идём": True,
            "тема": тема,
            "сайты": найти_сайт((реплика or "").lower()),
            "просили": True,
            "запрос_судьи": (с.get("запрос") or "").strip(),
        }
    return р


def очистить_запрос(реплика: str) -> str:
    """Убрать из реплики служебные слова, чтобы искать по сути.

    «найди в интернете какая погода в Тбилиси» → «какая погода в Тбилиси»
    """
    т = реплика or ""
    # \w* дочищает окончание: «в интернет» + «е» → убирается целиком
    for ф in sorted(_ПРОСЬБА_ИСКАТЬ, key=len, reverse=True):
        т = re.sub(re.escape(ф) + r"\w*", " ", т, flags=re.IGNORECASE)
    for г in _ГЛАГОЛЫ_ПОИСКА:
        т = re.sub(r"\b" + re.escape(г) + r"\w*\s*", " ", т, flags=re.IGNORECASE)
    т = _НА_САЙТЕ.sub(" ", т)
    # «на Ленте», «на Хабре» — тоже служебное, в запрос не нужно
    for ключ, _ in _САЙТЕ_ключи():
        т = re.sub(r"\bна\s+" + re.escape(ключ) + r"\w*\s*", " ", т, flags=re.IGNORECASE)
    т = re.sub(r"\s+", " ", т).strip(" ,.!?")
    return т


